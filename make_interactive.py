"""
make_interactive.py — 生成交互式篮球轨迹浏览器

生成同一个交互式 HTML 浏览器 (basketball_interactive.html)：(角度 × 后旋)
扫描、frames + 滑块、结局颜色区分；轨迹数据使用统一的 simulation.py。

功能:

    * 参数化 main(out_html, include_plotlyjs, angles/backspins/speed 覆盖):
      原版全部是模块常量 + 写死文件名; 现在可编程调用
    * CLI: --offline / --embed 生成内嵌 plotly.js 的离线版 (~3.5 MB);
           --out <html> 指定输出文件; --cdn 保持默认
    * 未知结局串不再 KeyError: 用灰色兜底并警告 (模型加新结局时 HTML 仍可生成)
    * 输入校验: DOWNSAMPLE>=1, 网格非空; 无轨迹时清晰报错
    * HTML 自带页面语言 (lang="zh-CN")、<title>、viewport/description/生成时间 meta、
      Plotly 来源注释、以及页面顶部用法横幅和底部 provenance 页脚 —— 浏览器打开即知
      它来自 make_interactive.py、参数网格、需要联网 CDN 加载 plotly.js
    * 生成逻辑包含 frame 顺序 / hovertemplate / shapes / slider steps / layout

依赖: numpy, plotly (pip install plotly)。
    python make_interactive.py                  # CDN 版 (默认)
    python make_interactive.py --offline        # 离线内嵌版
    python make_interactive.py --out my.html    # 自定义输出名
    python make_interactive.py --date 2026-10-22  # 固定页脚生成日期 (默认取今天)
"""

import argparse
import datetime as _dt
import sys
from pathlib import Path

import numpy as np

try:
    import plotly.graph_objects as go
except ImportError:
    raise SystemExit("缺少 plotly, 请先运行:  pip install plotly")

from simulation import simulate_shot
from physics import release_velocity
from collision import (RIM_CENTER, RIM_HEIGHT, RIM_RADIUS,
                       BACKBOARD_X, BACKBOARD_BOTTOM, BACKBOARD_TOP)

# ---------------------------------------------------------------------------
# 扫描参数 (可被 main()/CLI 覆盖)
# ---------------------------------------------------------------------------
ANGLES_DEG = np.arange(40.0, 61.0, 5.0)      # 出手角度 40..60°
BACKSPINS = np.arange(0.0, 41.0, 10.0)       # 后旋 0..40 rad/s
RELEASE_POS = (-4.57, 2.0, 0.0)              # 出手点 (标准罚球)
SPEED = 7.5                                  # 出手速率 [m/s]
DOWNSAMPLE = 4                               # 每隔几个轨迹点取 1 个, 控制 HTML 体积
OUT_HTML = "basketball_interactive.html"

# include_plotlyjs:
#   "cdn"  -> 文件小 (几十 KB), 但浏览器需联网加载 plotly.js
#   True   -> 完全离线可用, 但文件约 3.5 MB (内嵌 plotly.js)
INCLUDE_PLOTLYJS = "cdn"

OUTCOME_COLORS = {
    "swish": "#2ca02c",      # 绿
    "rim-in": "#ff7f0e",     # 橙
    "board-in": "#1f77b4",   # 蓝
    "miss": "#9e9e9e",       # 灰
}
OUTCOME_LABELS = {
    "swish": "空心", "rim-in": "弹框进",
    "board-in": "打板进", "miss": "未进",
}
FALLBACK_COLOR = "#9e9e9e"
FALLBACK_LABEL = "未知"

# 页面 chrome（lang/meta/横幅/页脚）。payload 保持 Plotly 生成的原样，只做字符串注入，
# 因此 addFrames / animate / bdata 等字节内容不变；重复运行只换 Plotly 的随机 div id。
PAGE_TITLE = "篮球投篮轨迹浏览器（角度×后旋扫描） — COMP1110 纯物理模拟"
HEADER_BANNER = (
    '<div style="height:auto;padding:10px 16px;background:#111722;color:#F0F4F8;'
    'font-family:system-ui,-apple-system,\\"Segoe UI\\",sans-serif;line-height:1.5">'
    '<b style="font-size:15px">篮球投篮轨迹浏览器 — 出手角度 × 后旋</b><br>'
    '拖动底部滑块切换 (θ, ω)；颜色=结局：'
    '<span style="color:#2ca02c">绿 swish</span> / '
    '<span style="color:#ff7f0e">橙 rim-in</span> / '
    '<span style="color:#1f77b4">蓝 board-in</span> / '
    '<span style="color:#9e9e9e">灰 miss</span>。'
    '悬停看 θ/ω/结局；坐标为米，x 由投手指向篮筐。'
    '</div>'
)
FOOTER_NOTE = (
    '<div style="padding:8px 16px;color:#93A0AF;'
    'font:12px/1.5 system-ui,-apple-system,\\"Segoe UI\\",sans-serif;'
    'border-top:1px solid #ddd">由 <code>make_interactive.py</code> 生成（{date}，'
    'Plotly {plotly_kind}）：网格 角度 {angles}° × 后旋 {backspins} rad/s、'
    '固定 {speed} m/s 罚球、出手点 {pos}、轨迹 {downsample} 倍降采样。'
    'CDN 版需联网加载 plotly.js；用 <code>--offline</code> 可生成完全离线内嵌版。'
    '本页仅为 3D 主流程可视化，与常数不同的 2D 演示模型不可互比（见 README §4）。'
    '</div>'
)


def enhance_html(html: str, *, title: str, date: str, plotly_kind: str,
                 angles: str, backspins: str, speed: str, pos: str,
                 downsample: str) -> str:
    """给 Plotly 的 full_html 注入 lang / head meta / 顶部用法横幅 / 底部 provenance 页脚。

    只改页面外层 chrome，不触碰 Plotly 的 trace/frame 载荷，保证内容仍与 make_interactive
    生成的一致。对缺少 <html>/<head>/<body> 锚点的输入原样返回（防御性，不崩）。
    """
    meta_block = (
        f'<title>{title}</title>\n'
        '    <meta name="viewport" content="width=device-width, initial-scale=1" />\n'
        f'    <meta name="description" content="COMP1110 pure-physics basketball shot '
        f'simulation: interactive Plotly sweep over release angle ({angles}) x backspin '
        f'({backspins}) at {speed} m/s free throw. Outcome colors: swish green, rim-in '
        'orange, board-in blue, miss gray. Generated by make_interactive.py, '
        f'{date}." />\n'
        '    <!-- Generated by make_interactive.py; payload is Plotly traces/frames '
        '(byte-unchanged). Outcome colors: swish green, rim-in orange, board-in blue, '
        'miss gray; hover shows theta/omega/label. CDN build needs internet for '
        'cdn.plot.ly plotly.js. -->\n'
    )

    # lang
    if "<html>" in html:
        html = html.replace("<html>", '<html lang="zh-CN">', 1)
    # head
    if "</head>" in html:
        html = html.replace("</head>", meta_block + "</head>", 1)
    # body chrome
    if "<body>" in html:
        html = html.replace("<body>", "<body>\n" + HEADER_BANNER, 1)
    if "</body>" in html:
        footer = FOOTER_NOTE.format(date=date, plotly_kind=plotly_kind, angles=angles,
                                    backspins=backspins, speed=speed, pos=pos,
                                    downsample=downsample)
        html = html.replace("</body>", footer + "</body>", 1)
    return html


def compute_trajectory(angle_deg, backspin, release_pos=RELEASE_POS,
                       speed=SPEED, downsample=DOWNSAMPLE):
    """跑一次投篮, 返回 (xs, ys, outcome)。downsample>=1 (改进校验)。"""
    if int(downsample) < 1:
        raise ValueError(f"downsample must be >= 1, got {downsample!r}")
    downsample = int(downsample)
    pos = np.asarray(release_pos, dtype=float)
    if pos.shape != (3,) or not np.all(np.isfinite(pos)):
        raise ValueError(f"release_pos must be a finite shape (3,) vector, got {pos!r}")
    speed = float(speed)
    if not np.isfinite(speed) or speed <= 0.0:
        raise ValueError(f"speed must be positive finite, got {speed!r}")
    v0 = release_velocity(speed, angle_deg)
    res = simulate_shot(pos, v0, backspin)
    xs = res["states"][:, 0][::downsample]
    ys = res["states"][:, 1][::downsample]
    return xs, ys, res["outcome"]


def _scatter_for(ang, back, xs, ys, outcome):
    """单条轨迹的 Scatter (frame / 初始图共用构造, 与原版字段逐项一致)。"""
    if outcome not in OUTCOME_COLORS:
        print(f"  警告: 模型给出未知结局 {outcome!r} "
              f"(θ={ang:.0f}°, ω={back:.0f}) — 用灰色兜底, HTML 仍可生成")
    return go.Scatter(
        x=xs, y=ys, mode="lines",
        line=dict(color=OUTCOME_COLORS.get(outcome, FALLBACK_COLOR), width=2.5),
        name=f"{ang:.0f}_{back:.0f}",
        hovertemplate=(
            f"θ={ang:.0f}°  ω={back:.0f} rad/s  "
            f"结局: {OUTCOME_LABELS.get(outcome, FALLBACK_LABEL)}<extra></extra>"),
    )


def main(out_html: str = OUT_HTML, include_plotlyjs: str | bool = INCLUDE_PLOTLYJS,
         angles_deg=None, backspins=None, release_pos=RELEASE_POS,
         speed=SPEED, downsample=DOWNSAMPLE, date=None):
    """生成 HTML 浏览器。返回输出路径。 (扫描/布局构造与原版逐字段一致)"""
    angles_deg = np.asarray(angles_deg if angles_deg is not None
                            else ANGLES_DEG, dtype=float).reshape(-1)
    backspins = np.asarray(backspins if backspins is not None
                           else BACKSPINS, dtype=float).reshape(-1)
    if angles_deg.size == 0 or backspins.size == 0:
        raise ValueError("角度/后旋网格不能为空")

    out_path = Path(out_html)
    if str(out_path.parent) not in ("", ".") and not out_path.parent.is_dir():
        raise FileNotFoundError(f"输出目录不存在: {out_path.parent}")

    # 1) 扫描并计算所有轨迹 (后旋外层 → 拖动滑块时主要扫过角度, 视觉变化更明显)
    trajs = []
    for back in backspins:
        for ang in angles_deg:
            xs, ys, outcome = compute_trajectory(ang, back, release_pos,
                                                 speed, downsample)
            trajs.append((ang, back, xs, ys, outcome))
    if not trajs:
        raise ValueError("没有产出任何轨迹 (网格为空?)")

    # 2) 每条轨迹一个 frame
    frames = [go.Frame(data=[_scatter_for(ang, back, xs, ys, outcome)],
                       name=f"{ang:.0f}_{back:.0f}")
              for ang, back, xs, ys, outcome in trajs]

    # 3) 初始图 (第一条轨迹) — 与原版一致: 无 name (原版初始 Scatter 未带 name)
    ang0, back0, xs0, ys0, out0 = trajs[0]
    fig = go.Figure(
        data=[go.Scatter(
            x=xs0, y=ys0, mode="lines",
            line=dict(color=OUTCOME_COLORS.get(out0, FALLBACK_COLOR), width=2.5),
        )],
        frames=frames,
    )

    # 4) 静态几何: 篮板 (竖线) + 篮筐 (横线), 存在 layout 里, 不随 frame 变化
    shapes = [
        dict(type="line",
             x0=BACKBOARD_X, y0=BACKBOARD_BOTTOM,
             x1=BACKBOARD_X, y1=BACKBOARD_TOP,
             line=dict(color="black", width=3)),
        dict(type="line",
             x0=RIM_CENTER[0] - RIM_RADIUS, y0=RIM_HEIGHT,
             x1=RIM_CENTER[0] + RIM_RADIUS, y1=RIM_HEIGHT,
             line=dict(color="red", width=4)),
    ]

    # 5) 滑块 steps
    steps = [dict(
        method="animate",
        args=[[f"{ang:.0f}_{back:.0f}"],
              {"frame": {"duration": 0, "redraw": True},
               "mode": "immediate",
               "transition": {"duration": 0}}],
        label=f"{ang:.0f}/{back:.0f}",
    ) for ang, back, _xs, _ys, _outcome in trajs]

    sliders = [dict(
        active=0,
        steps=steps,
        currentvalue={"prefix": "出手参数 (角度°/后旋 rad/s): "},
        pad=dict(t=60),
    )]

    fig.update_layout(
        title="篮球轨迹浏览器 — 拖动滑块查看不同出手参数",
        xaxis=dict(title="x (m)  [投手 → 篮筐]", range=[-4.7, 0.6]),
        yaxis=dict(title="y (m)", range=[0.0, 4.6]),
        shapes=shapes,
        sliders=sliders,
        showlegend=False,
        height=640,
    )

    # 颜色图例说明
    fig.add_annotation(
        text="绿=空心(swish)  橙=弹框进(rim-in)  蓝=打板进(board-in)  灰=未进(miss)",
        xref="paper", yref="paper", x=0.99, y=0.98,
        xanchor="right", yanchor="top",
        showarrow=False, font=dict(size=11),
        bgcolor="rgba(255,255,255,0.7)",
    )

    # 6) 渲染：先写 Plotly 完整 HTML，再注入 lang/meta/横幅/页脚（payload 逐字不变）。
    date_str = date or _dt.date.today().isoformat()
    step_a = float(angles_deg[1] - angles_deg[0]) if angles_deg.size > 1 else 0.0
    step_b = float(backspins[1] - backspins[0]) if backspins.size > 1 else 0.0
    angles_desc = (f"{float(angles_deg[0]):g}..{float(angles_deg[-1]):g}°"
                   + (f" (step {step_a:g}°)" if angles_deg.size > 1 else ""))
    backspins_desc = (f"{float(backspins[0]):g}..{float(backspins[-1]):g} rad/s"
                      + (f" (step {step_b:g})" if backspins.size > 1 else ""))
    html = fig.to_html(full_html=True, include_plotlyjs=include_plotlyjs,
                       default_height="640", default_width="100%")
    kind = "CDN, 需联网" if include_plotlyjs == "cdn" else "离线内嵌"
    html = enhance_html(
        html, title=PAGE_TITLE, date=date_str, plotly_kind=kind,
        angles=angles_desc, backspins=backspins_desc,
        speed=f"{float(speed):g} m/s", pos=str(tuple(release_pos)),
        downsample=f"{int(downsample)}",
    )
    out_path.write_text(html, encoding="utf-8")
    print(f"已生成 {out_path}  ({len(trajs)} 条轨迹, plotly.js={kind}, "
          f"含 lang/meta + 页脚 provenance)")
    return out_path


if __name__ == "__main__":
    ap = argparse.ArgumentParser(
        description="生成交互式篮球轨迹 HTML")
    ap.add_argument("--out", default=OUT_HTML, help="输出 HTML 路径")
    ap.add_argument("--offline", "--embed", action="store_true",
                    help="内嵌 plotly.js (文件大, 完全离线)")
    ap.add_argument("--cdn", action="store_true", help="用 CDN (默认)")
    ap.add_argument("--date", default=None,
                    help="页脚生成日期 (YYYY-MM-DD，默认取今天)")
    ns = ap.parse_args()
    include = True if ns.offline else INCLUDE_PLOTLYJS
    main(out_html=ns.out, include_plotlyjs=include, date=ns.date)
